// Existing Japanese and English WMO labels, preserved verbatim.
use serde_json::Value;
pub fn weather(code: &Value, language: &str) -> &'static str {
    let code = code
        .as_f64()
        .filter(|n| n.fract() == 0.0 && *n >= 0.0 && *n <= 99.0)
        .map(|n| n as i32);
    match (code, language) {
        (Some(0), "ja") => "快晴",
        (Some(1), "ja") => "晴れ",
        (Some(2), "ja") => "晴れ時々くもり",
        (Some(3), "ja") => "くもり",
        (Some(45), "ja") => "霧",
        (Some(48), "ja") => "霧",
        (Some(51), "ja") => "小雨",
        (Some(53), "ja") => "雨",
        (Some(55), "ja") => "強い雨",
        (Some(56), "ja") => "弱い着氷性の霧雨",
        (Some(57), "ja") => "強い着氷性の霧雨",
        (Some(61), "ja") => "小雨",
        (Some(63), "ja") => "雨",
        (Some(65), "ja") => "強い雨",
        (Some(66), "ja") => "弱い着氷性の雨",
        (Some(67), "ja") => "強い着氷性の雨",
        (Some(71), "ja") => "小雪",
        (Some(73), "ja") => "雪",
        (Some(75), "ja") => "大雪",
        (Some(77), "ja") => "霧雪",
        (Some(80), "ja") => "にわか雨",
        (Some(81), "ja") => "にわか雨",
        (Some(82), "ja") => "強いにわか雨",
        (Some(85), "ja") => "にわか雪",
        (Some(86), "ja") => "強いにわか雪",
        (Some(95), "ja") => "雷雨",
        (Some(96), "ja") => "雷雨",
        (Some(99), "ja") => "激しい雷雨",
        (Some(0), "en") => "Clear sky",
        (Some(1), "en") => "Mainly clear",
        (Some(2), "en") => "Partly cloudy",
        (Some(3), "en") => "Overcast",
        (Some(45), "en") => "Fog",
        (Some(48), "en") => "Depositing rime fog",
        (Some(51), "en") => "Light drizzle",
        (Some(53), "en") => "Moderate drizzle",
        (Some(55), "en") => "Dense drizzle",
        (Some(56), "en") => "Light freezing drizzle",
        (Some(57), "en") => "Dense freezing drizzle",
        (Some(61), "en") => "Slight rain",
        (Some(63), "en") => "Moderate rain",
        (Some(65), "en") => "Heavy rain",
        (Some(66), "en") => "Light freezing rain",
        (Some(67), "en") => "Heavy freezing rain",
        (Some(71), "en") => "Slight snow",
        (Some(73), "en") => "Moderate snow",
        (Some(75), "en") => "Heavy snow",
        (Some(77), "en") => "Snow grains",
        (Some(80), "en") => "Slight rain showers",
        (Some(81), "en") => "Moderate rain showers",
        (Some(82), "en") => "Violent rain showers",
        (Some(85), "en") => "Slight snow showers",
        (Some(86), "en") => "Heavy snow showers",
        (Some(95), "en") => "Thunderstorm",
        (Some(96), "en") => "Thunderstorm with slight hail",
        (Some(99), "en") => "Thunderstorm with heavy hail",
        (_, "ja") => "不明",
        _ => "Unknown",
    }
}
